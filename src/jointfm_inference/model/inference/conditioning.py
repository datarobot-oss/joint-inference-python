"""Analytic Student-t mixture conditioning used by ``PredictorAdapter.condition``.

Conditions a joint Student-t mixture on known values of a subset of the
variables of one emission position and returns reduced-space parameters over
the unknown variables.

Both covariance parameterizations are conditionable: a full Cholesky factor,
and the diagonal-plus-factor form ``Sigma = diag(d) + U U^T``. The latter takes
a Woodbury reduction that never materializes ``Sigma`` and solves an ``r x r``
system in place of a ``D x D`` one. Either way the conditional is returned as a
Cholesky factor over the unknown block.

The conditional location and scale come from the Schur complement of the
observed block; the conditional additionally raises the degrees of freedom and
inflates the scale by the observed block's squared Mahalanobis distance
(Azzalini & Capitanio, 2003).

*Refs: Ding (2016), "On the Conditional Distribution of the Multivariate t
Distribution" (arXiv:1604.00561), for the closed form implemented here;
Azzalini & Capitanio (2003), "Distributions generated by perturbation of
symmetry with emphasis on a multivariate skew t-distribution", for the
elliptical statement above.*
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Mapping, Optional, Tuple

import torch
import torch.nn.functional as F

from jointfm_inference.model.linalg import cholesky_from_lowrank, robust_cholesky


@dataclass(frozen=True)
class MixtureCovariance:
    """One mixture's component scale matrices in one of two parameterizations.

    The head emits the diagonal-plus-factor pair ``Sigma = diag(d) + U U^T``;
    a conditioned mixture carries a full lower-triangular Cholesky factor.
    Conditioning accepts both, so this is the covariance argument every entry
    point in this module takes, and the "exactly one parameterization"
    invariant is checked here once.

    Attributes:
        chol: ``(..., K, D, D)`` lower-triangular factor, or ``None`` when the
            head emitted the diagonal-plus-factor form.
        lowrank_diag: ``(..., K, D)`` strictly positive diagonal in variance
            units, or ``None`` when the head emitted a Cholesky factor.
        lowrank_U: ``(..., K, D, r)`` covariance factor, always paired with
            ``lowrank_diag``.

    Raises:
        ValueError: when neither or both parameterizations are supplied, or when
            only one half of the diagonal-plus-factor pair is.
    """

    chol: Optional[torch.Tensor] = None
    lowrank_diag: Optional[torch.Tensor] = None
    lowrank_U: Optional[torch.Tensor] = None

    def __post_init__(self) -> None:
        """Reject any covariance that is not exactly one complete parameterization."""
        lowrank_parts = (self.lowrank_diag is not None) + (self.lowrank_U is not None)
        if lowrank_parts == 1:
            raise ValueError(
                "MixtureCovariance requires lowrank_diag and lowrank_U together"
            )
        if (self.chol is not None) == (lowrank_parts == 2):
            raise ValueError(
                "MixtureCovariance takes exactly one parameterization: a full "
                "Cholesky factor or a lowrank_diag/lowrank_U pair"
            )

    @classmethod
    def from_params(cls, params: Mapping[str, torch.Tensor]) -> "MixtureCovariance":
        """Read the covariance out of a mixture head's emitted parameter mapping.

        Raises:
            KeyError: when the mapping carries neither parameterization, which
                means the head is not one this module conditions.
        """
        if "chol" in params:
            return cls(chol=params["chol"])
        if "lowrank_diag" in params:
            return cls(
                lowrank_diag=params["lowrank_diag"], lowrank_U=params["lowrank_U"]
            )
        raise KeyError(
            "Mixture parameters carry neither 'chol' nor 'lowrank_diag'/'lowrank_U'"
        )

    @property
    def is_lowrank(self) -> bool:
        """Whether the head emitted the diagonal-plus-factor parameterization."""
        return self.lowrank_diag is not None

    def lowrank_parts(self) -> Tuple[torch.Tensor, torch.Tensor]:
        """Return ``(lowrank_diag, lowrank_U)`` for the diagonal-plus-factor form."""
        if self.lowrank_diag is None or self.lowrank_U is None:
            raise RuntimeError(
                "MixtureCovariance does not carry a diagonal-plus-factor covariance"
            )
        return self.lowrank_diag, self.lowrank_U

    def dense_chol(self) -> torch.Tensor:
        """Return a full Cholesky factor, factorizing the low-rank form if needed.

        Only the degenerate no-known-variable path needs this: conditioning is
        then a no-op, but the return contract is a Cholesky factor either way.
        """
        if self.chol is not None:
            return self.chol
        lowrank_diag, lowrank_U = self.lowrank_parts()
        return cholesky_from_lowrank(lowrank_diag, lowrank_U)

    def flatten_to(
        self, b_flat: int, n_components: int, n_vars: int
    ) -> "MixtureCovariance":
        """Collapse the leading axes to one batch axis, keeping the parameterization."""
        if self.chol is not None:
            return MixtureCovariance(
                chol=self.chol.reshape(b_flat, n_components, n_vars, n_vars)
            )
        lowrank_diag, lowrank_U = self.lowrank_parts()
        return MixtureCovariance(
            lowrank_diag=lowrank_diag.reshape(b_flat, n_components, n_vars),
            lowrank_U=lowrank_U.reshape(
                b_flat, n_components, n_vars, lowrank_U.shape[-1]
            ),
        )


@dataclass(frozen=True)
class _FlatMixture:
    """One mixture flattened to a single batch axis with its known/unknown split.

    Callers guarantee a mask that is uniform across the leading axes, so the
    partition is one pair of index vectors shared by every flattened row
    rather than a per-row gather.

    Attributes:
        batch_shape: Leading axes that flattening removed, restored on return.
        logits: Mixture logits ``(B_flat, K)``.
        means: Component locations ``(B_flat, K, D)``.
        covariance: Component scale matrices in whichever parameterization the
            head emitted, with the same leading-axis flattening applied.
        values: Known values ``(B_flat, D)``; entries outside ``idx_a`` are unused.
        idx_a: Indices of the known (observed) variables.
        idx_b: Indices of the unknown variables.
    """

    batch_shape: Tuple[int, ...]
    logits: torch.Tensor
    means: torch.Tensor
    covariance: MixtureCovariance
    values: torch.Tensor
    idx_a: torch.Tensor
    idx_b: torch.Tensor


@dataclass(frozen=True)
class _EllipticalConditional:
    """Schur-complement quantities of one Student-t mixture conditional.

    Attributes:
        mahalanobis: ``(B_flat, K)`` squared Mahalanobis distance of the observed
            block under each component -- the quadratic form an elliptical
            conditional's density generator depends on.
        log_det_aa: ``(B_flat, K)`` log-determinant of each component's
            observed-block scale submatrix.
        mu_b_cond: ``(B_flat, K, Db)`` conditional locations, or ``None`` when
            every variable is known and there is no unknown block left.
        sigma_b_cond: ``(B_flat, K, Db, Db)`` Schur complement, ``None`` under
            the same condition: the *uninflated* conditional scale matrix.
    """

    mahalanobis: torch.Tensor
    log_det_aa: torch.Tensor
    mu_b_cond: Optional[torch.Tensor]
    sigma_b_cond: Optional[torch.Tensor]


def _gather_block(
    matrices: torch.Tensor, idx_rows: torch.Tensor, idx_cols: torch.Tensor
) -> torch.Tensor:
    """Gather one batched covariance submatrix for the requested indices."""
    B_flat, K, _, D_mat = matrices.shape
    n_rows = int(idx_rows.numel())
    n_cols = int(idx_cols.numel())

    row_idx = idx_rows.view(1, 1, n_rows, 1).expand(B_flat, K, n_rows, D_mat)
    rows = matrices.gather(-2, row_idx)

    col_idx = idx_cols.view(1, 1, 1, n_cols).expand(B_flat, K, n_rows, n_cols)
    return rows.gather(-1, col_idx)


def _flatten_mixture(
    logits: torch.Tensor,
    means: torch.Tensor,
    covariance: MixtureCovariance,
    values: torch.Tensor,
    mask: torch.Tensor,
) -> _FlatMixture:
    """Flatten the leading batch axes and read the known/unknown split off the mask.

    The partition is taken from the first flattened row, which is exact only
    because callers pass a mask that is uniform across the leading axes.
    """
    batch_shape = logits.shape[:-1]
    K = logits.shape[-1]
    D = means.shape[-1]
    B_flat = logits.numel() // K

    if mask.dim() == 1 and mask.shape[0] == D:
        mask_flat = mask.unsqueeze(0).expand(B_flat, D)
    else:
        mask_flat = mask.broadcast_to(batch_shape + (D,)).reshape(B_flat, D)
    first_mask = mask_flat[0]

    return _FlatMixture(
        batch_shape=batch_shape,
        logits=logits.reshape(B_flat, K),
        means=means.reshape(B_flat, K, D),
        covariance=covariance.flatten_to(B_flat, K, D),
        values=values.reshape(B_flat, D),
        idx_a=torch.nonzero(first_mask).squeeze(1),
        idx_b=torch.nonzero(~first_mask).squeeze(1),
    )


def _elliptical_conditional(flat: _FlatMixture) -> _EllipticalConditional:
    """Solve the observed block and Schur-complement the unknown one.

    Dispatches on the parameterization the head emitted. Both branches return
    the same quantities over the same partition, so everything downstream of
    this call is parameterization-agnostic.
    """
    if flat.covariance.is_lowrank:
        return _lowrank_conditional(flat)
    return _dense_conditional(flat)


def _lowrank_conditional(flat: _FlatMixture) -> _EllipticalConditional:
    """Schur-complement the diagonal-plus-factor form without ever building Sigma.

    With ``Sigma = diag(d) + U U^T`` the diagonal contributes nothing off-block,
    so ``Sigma_ba = U_b U_a^T`` and the Woodbury identity (the closed form for
    the inverse of a low-rank update to an invertible matrix) collapses the
    whole observed-block solve onto the ``r x r`` matrix
    ``M = (I + U_a^T diag(d_a)^-1 U_a)^-1``. Writing ``proj = U_a^T
    diag(d_a)^-1 (x_a - mu_a)``, all four quantities this returns follow from
    one Cholesky ``L_m L_m^T = I + U_a^T diag(d_a)^-1 U_a``:

    - the Schur complement is ``diag(d_b) + U_b M U_b^T``,
    - the location shift is ``U_b M proj``,
    - the observed block's squared Mahalanobis distance is its diagonal value
      ``sum((x_a - mu_a)^2 / d_a)`` less ``proj^T M proj``,
    - ``log det Sigma_aa`` is ``sum(log d_a) - log det M`` by the matrix
      determinant lemma.

    That costs ``O(p r^2 + r^3)`` against the dense path's ``O(D^3)``, and no
    ``(B_flat, K, D, D)`` tensor is materialized at any point.

    The conditional provably keeps the diagonal-plus-factor form at the same
    rank, as ``diag(d_b) + (U_b L_m^-T)(U_b L_m^-T)^T``. It is still returned as
    a dense Schur complement over the unknown block, which is strictly smaller
    than the joint: every consumer of a conditioned adapter factorizes a
    low-rank covariance on entry anyway, so returning the factor would only move
    the same factorization into each later ``sample`` or ``log_prob`` call and
    repeat it per call.
    """
    lowrank_diag, lowrank_U = flat.covariance.lowrank_parts()

    diag_a = lowrank_diag[..., flat.idx_a]
    factor_a = lowrank_U[..., flat.idx_a, :]
    rank = lowrank_U.shape[-1]

    delta_a = flat.values[..., flat.idx_a].unsqueeze(1) - flat.means[..., flat.idx_a]
    scaled_delta_a = delta_a / diag_a

    gram = torch.matmul(factor_a.transpose(-1, -2), factor_a / diag_a.unsqueeze(-1))
    identity = torch.eye(rank, device=gram.device, dtype=gram.dtype)
    L_m = robust_cholesky(identity + gram)

    proj = torch.matmul(factor_a.transpose(-1, -2), scaled_delta_a.unsqueeze(-1))
    whitened_proj = torch.linalg.solve_triangular(L_m, proj, upper=False)

    mahalanobis = (delta_a * scaled_delta_a).sum(dim=-1) - (
        whitened_proj.squeeze(-1) ** 2
    ).sum(dim=-1)
    log_det_aa = diag_a.log().sum(dim=-1) + 2 * torch.diagonal(
        L_m, dim1=-2, dim2=-1
    ).log().sum(dim=-1)

    if flat.idx_b.numel() == 0:
        return _EllipticalConditional(
            mahalanobis=mahalanobis,
            log_det_aa=log_det_aa,
            mu_b_cond=None,
            sigma_b_cond=None,
        )

    diag_b = lowrank_diag[..., flat.idx_b]
    factor_b = lowrank_U[..., flat.idx_b, :]

    solved_proj = torch.linalg.solve_triangular(
        L_m.transpose(-1, -2), whitened_proj, upper=True
    )
    mu_b_cond = flat.means[..., flat.idx_b] + torch.matmul(
        factor_b, solved_proj
    ).squeeze(-1)

    rotated = torch.linalg.solve_triangular(
        L_m, factor_b.transpose(-1, -2), upper=False
    )
    sigma_b_cond = torch.diag_embed(diag_b) + torch.matmul(
        rotated.transpose(-1, -2), rotated
    )

    return _EllipticalConditional(
        mahalanobis=mahalanobis,
        log_det_aa=log_det_aa,
        mu_b_cond=mu_b_cond,
        sigma_b_cond=sigma_b_cond,
    )


def _dense_conditional(flat: _FlatMixture) -> _EllipticalConditional:
    """Solve the observed block and take the unknown block's Schur complement.

    The scale matrix is reconstructed from the emitted Cholesky factor and
    re-factorized on the observed block, because the partition reorders
    variables and a submatrix of a Cholesky factor is not the Cholesky factor
    of the corresponding submatrix.

    The observed block goes through ``robust_cholesky``, as does the returned
    Schur complement in each public entry point, so this surface stabilizes
    covariances exactly as every other caller in the repo does. That matters
    beyond consistency: the stabilization floor is added to the *returned*
    conditional covariance, and a strongly dependent pair has a conditional
    variance far below unit scale, so a floor chosen for unit-scale matrices
    inflates such a block by a multiple of its true value rather than
    perturbing it.
    """
    chol = flat.covariance.chol
    if chol is None:
        raise RuntimeError("_dense_conditional requires a full Cholesky factor")
    sigma = torch.matmul(chol, chol.transpose(-1, -2))
    sigma_aa = _gather_block(sigma, flat.idx_a, flat.idx_a)
    L_aa = robust_cholesky(sigma_aa)

    mu_a = flat.means[..., flat.idx_a]
    x_a = flat.values[..., flat.idx_a].unsqueeze(1)
    delta_a = (x_a - mu_a).unsqueeze(-1)
    whitened = torch.linalg.solve_triangular(L_aa, delta_a, upper=False).squeeze(-1)

    mahalanobis = (whitened**2).sum(dim=-1)
    log_det_aa = 2 * torch.diagonal(L_aa, dim1=-2, dim2=-1).log().sum(dim=-1)

    if flat.idx_b.numel() == 0:
        return _EllipticalConditional(
            mahalanobis=mahalanobis,
            log_det_aa=log_det_aa,
            mu_b_cond=None,
            sigma_b_cond=None,
        )

    sigma_ab = _gather_block(sigma, flat.idx_a, flat.idx_b)
    sigma_ba = _gather_block(sigma, flat.idx_b, flat.idx_a)
    sigma_bb = _gather_block(sigma, flat.idx_b, flat.idx_b)

    solved_a = torch.linalg.solve_triangular(
        L_aa.transpose(-2, -1), whitened.unsqueeze(-1), upper=True
    )
    mu_b_cond = flat.means[..., flat.idx_b] + torch.matmul(sigma_ba, solved_a).squeeze(
        -1
    )

    whitened_ab = torch.linalg.solve_triangular(L_aa, sigma_ab, upper=False)
    sigma_b_cond = sigma_bb - torch.matmul(whitened_ab.transpose(-2, -1), whitened_ab)

    return _EllipticalConditional(
        mahalanobis=mahalanobis,
        log_det_aa=log_det_aa,
        mu_b_cond=mu_b_cond,
        sigma_b_cond=sigma_b_cond,
    )


def _empty_unknown_block(
    new_log_pi: torch.Tensor, flat: _FlatMixture
) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """Shape the all-known result: posterior weights over zero-width parameters."""
    batch_shape = flat.batch_shape
    K = flat.logits.shape[-1]
    device = flat.logits.device
    dtype = flat.logits.dtype
    return (
        new_log_pi.reshape(*batch_shape, K),
        torch.zeros(*batch_shape, K, 0, device=device, dtype=dtype),
        torch.zeros(*batch_shape, K, 0, 0, device=device, dtype=dtype),
    )


def conditioned_log_density(logits: torch.Tensor) -> torch.Tensor:
    """Return the log density a conditioned mixture assigns to its known values.

    ``condition_student_t_mixture`` returns *unnormalized* log posterior
    weights: each one is the component's prior
    weight times its marginal density of the known block. Their normalizer is
    therefore the mixture's own marginal density at those values, which is the
    plausibility number a conditional query reports — the difference between
    "the model is confident" and "you conditioned on something the model finds
    absurd".

    Args:
        logits: ``(..., K)`` unnormalized log posterior weights, exactly as
            ``condition_student_t_mixture`` returns them.

    Returns:
        ``(...)`` log density of the known values under the unconditioned
        mixture.

    Passing the logits of an *unconditioned* mixture returns the log of their
    exponential sum, which is not a density; the caller owns that distinction,
    because nothing in the tensor records whether it was conditioned.
    """
    return torch.logsumexp(logits, dim=-1)


def condition_student_t_mixture(
    logits: torch.Tensor,
    means: torch.Tensor,
    covariance: MixtureCovariance,
    df: torch.Tensor,
    values: torch.Tensor,
    mask: torch.Tensor,
) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
    """Condition a symmetric multivariate Student-t mixture on a subset of variables.

    Every component takes the Schur-complement location shift and scale of its
    unknown block and gains exactly two scalars (Ding, 2016):
    the degrees of freedom rise from ``nu_k`` to ``nu_k + p`` over the ``p``
    known variables, and the conditional scale matrix is inflated by
    ``(nu_k + d_a_k) / (nu_k + p)``, where ``d_a_k`` is the known block's
    squared Mahalanobis distance under component ``k``. The inflation is what a
    stress slice asks for: residual spread widens exactly when the conditioning
    value was surprising under that component.

    The posterior mixture weights use each component's *marginal* t-density of
    the known block, which carries the component's own ``nu_k`` -- a
    multivariate-t marginal keeps the degrees of freedom of the joint.

    The mixture is over the ``D`` variables of one emission position. The
    leading batch axes are conditioned independently, so this function carries
    no notion of dependence across them.

    Args:
        logits: (..., K)
        means: (..., K, D)
        covariance: Component scale matrices, either as a full
            ``(..., K, D, D)`` lower-triangular Cholesky factor or as the
            diagonal-plus-factor pair ``Sigma = diag(d) + U U^T``
        df: (..., K) degrees of freedom, strictly positive
        values: (..., D) known values
        mask: (..., D) boolean mask of known dimensions (True = known)

    Returns:
        (new_logits, new_means, new_chol, new_df) over unknown dimensions.
        Shapes: (..., K), (..., K, Db), (..., K, Db, Db), (..., K).
        ``new_chol`` is a full Cholesky factor whichever parameterization
        came in, at the reduced width ``Db``.
        ``new_chol`` factorizes the *inflated* conditional scale matrix, so the
        returned tuple is a plain Student-t mixture that any consumer of the
        head's parameter mapping can sample or score unchanged. ``new_logits``
        are unnormalized log posterior weights. When no dimension is known the
        inputs are returned unchanged; when every dimension is known the means
        and Cholesky factors come back empty along the variable axis while the
        weights and the raised degrees of freedom still carry information.

    Invariant:
        The partition is read from the first flattened batch row, so callers
        must pass a mask that is uniform across the leading axes;
        ``PredictorAdapter.condition`` enforces this.

    The scale inflation is applied to the *factor* rather than to the matrix,
    which is exact because a positive scalar multiple of a covariance has that
    same multiple's square root times its Cholesky factor. Stabilization
    therefore acts on the uninflated Schur complement, where the floor of
    ``robust_cholesky`` means what it means everywhere else.

    Raises:
        ValueError: when ``df`` does not carry one value per component on the
            same leading axes as ``logits``, or when it is not strictly
            positive, which would make the marginal t-density of the known
            block undefined.
    """
    if df.shape != logits.shape:
        raise ValueError(
            "Student-t conditioning requires df shaped like logits (..., K); got "
            f"{tuple(df.shape)} against {tuple(logits.shape)}"
        )
    if not bool((df > 0).all().item()):
        raise ValueError(
            "Student-t conditioning requires strictly positive degrees of freedom"
        )

    flat = _flatten_mixture(logits, means, covariance, values, mask)
    K = flat.logits.shape[-1]
    df_flat = df.reshape(-1, K)

    if flat.idx_a.numel() == 0:
        return logits, means, covariance.dense_chol(), df

    conditional = _elliptical_conditional(flat)
    n_known = int(flat.idx_a.numel())

    log_prob_a = (
        torch.lgamma((df_flat + n_known) / 2.0)
        - torch.lgamma(df_flat / 2.0)
        - 0.5 * n_known * torch.log(df_flat * math.pi)
        - 0.5 * conditional.log_det_aa
        - 0.5 * (df_flat + n_known) * torch.log1p(conditional.mahalanobis / df_flat)
    )
    new_log_pi = F.log_softmax(flat.logits, dim=-1) + log_prob_a
    new_df_flat = df_flat + n_known

    batch_shape = flat.batch_shape
    mu_b_cond, sigma_b_cond = conditional.mu_b_cond, conditional.sigma_b_cond
    if mu_b_cond is None or sigma_b_cond is None:
        new_logits, new_means, new_chol = _empty_unknown_block(new_log_pi, flat)
        return new_logits, new_means, new_chol, new_df_flat.reshape(*batch_shape, K)

    inflation = (df_flat + conditional.mahalanobis) / new_df_flat
    L_b_cond = robust_cholesky(sigma_b_cond) * inflation.sqrt().reshape(
        *inflation.shape, 1, 1
    )

    n_unknown = int(flat.idx_b.numel())
    return (
        new_log_pi.reshape(*batch_shape, K),
        mu_b_cond.reshape(*batch_shape, K, n_unknown),
        L_b_cond.reshape(*batch_shape, K, n_unknown, n_unknown),
        new_df_flat.reshape(*batch_shape, K),
    )
